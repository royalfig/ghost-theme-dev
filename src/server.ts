const VERSION: string = JSON.parse(
  readFileSync(new URL("../package.json", import.meta.url), "utf-8"),
).version;

interface SiteData {
  url: string;
  title: string;
  version: string | null;
}

let siteData: SiteData | null = null;

function broadcast(wss: WebSocketServer, message: string): void {
  wss.clients.forEach((client) => {
    if (client.readyState === WebSocket.OPEN) {
      client.send(message);
    }
  });
}

export function printCompilationDetails(
  content: CompilationDetails,
  change?: string | null,
  firstTime = false,
) {
  if (firstTime) {
    console.log(chalk.dim(`┏━ Building...`));
    console.log(chalk.dim("┃"));
  } else {
    console.log(chalk.dim(`┏━ Change detected. Rebuilding... `));
    console.log(chalk.dim("┃"));
  }

  content.results.forEach(({ file, value }) => {
    console.log(
      chalk.dim(`┃`),
      ` ${
        change ? change + chalk.bold.magenta(" → ") : ""
      }${file} (${chalk.bold.magenta(value)})`,
    );
  });
  console.log(chalk.dim("┃"));
  console.log(
    `${chalk.dim("┗━ Done in")} ${content.time.toFixed(2)}ms ${chalk.dim(
      "at",
    )} ${new Date().toLocaleTimeString(undefined, { timeStyle: "short" })}\n`,
  );
}

export function printHeader(
  url: string,
  connectionError = false,
  firstConnection = false,
) {
  console.clear();
  console.log(
    `${chalk.bold.green("●")}  Ghost theme dev server running (v${VERSION})...`,
  );

  if (connectionError) {
    console.log(
      chalk.redBright.bold("✘  No connection. "),
      `Try refreshing your browser or visiting ${chalk.underline.blue(url)}.`,
    );
  } else if (firstConnection) {
    console.log(
      chalk.blueBright.bold("➜"),
      ` Connected to ${chalk.underline.blue(url)}.`,
    );
  } else if (siteData?.version) {
    console.log(
      chalk.blueBright.bold("➜"),
      ` Connected to ${chalk.underline.blue(siteData.url)} ${chalk.dim(
        `(${siteData.version})`,
      )}`,
    );
  } else {
    console.log(
      chalk.blueBright.bold("➜"),
      ` Visit ${chalk.underline.blue(url)} to see your changes live.`,
    );
  }
  console.log("");
}

/** Messages understood by the client in src/client.ts. */
export type ClientMessage =
  | {
      type: "css";
      files: string[];
      source: string;
      /** Critical CSS inlined into default.hbs, swapped into its <style> block. */
      inline?: { file: string; css: string }[];
    }
  | { type: "reload"; reason: string }
  | { type: "error"; file?: string; message: string }
  | { type: "notice"; message: string };

function send(wss: WebSocketServer, message: ClientMessage): void {
  broadcast(wss, JSON.stringify(message));
}

export function printProblems(res: CompilationDetails): void {
  const errors = res.errors ?? [];
  const warnings = res.warnings ?? [];
  if (errors.length > 0) {
    console.log(chalk.red.bold(`✘  Build failed (${errors.length} error${errors.length === 1 ? "" : "s"}). The browser keeps the previous version.`));
    console.log("");
    for (const e of errors) console.log(e.pretty);
    console.log("");
  }
  for (const w of warnings) console.log(w.pretty);
}

const DEBOUNCE_MS = 75;

type ChangeKind =
  | "layout" // default-template.hbs
  | "template" // any other .hbs
  | "source" // JS/TS/CSS that feeds an entry point
  | "image" // src/img
  | "asset" // static files under assets/ (fonts etc.)
  | "package"
  | "locale"
  | "ignore";

const IMAGE_RE = /\.(jpe?g|png|webp|avif|svg)$/i;
const SOURCE_RE = /\.(css|js|ts)$/i;

export function classifyChange(path: string, entries: Set<string>): ChangeKind {
  if (path === "default.hbs") return "ignore"; // generated by gtb
  if (path === "default-template.hbs") return "layout";
  if (path.endsWith(".hbs")) return "template";
  if (path.startsWith("src/img/") && IMAGE_RE.test(path)) return "image";
  if (SOURCE_RE.test(path) && !path.endsWith(".d.ts")) {
    if (path.startsWith("src/") || entries.has(path) || tree.has(path)) return "source";
    return "ignore";
  }
  if (path.startsWith("assets/") && !path.startsWith("assets/built/")) return "asset";
  if (path === "package.json") return "package";
  if (/^locales\/[^/]+\.json$/.test(path)) return "locale";
  return "ignore";
}

function verb(event: string): string {
  if (event === "add") return "added";
  if (event === "unlink") return "removed";
  return "changed";
}

export async function initWs(
  res: CompilationDetails,
  port: number,
  url: string,
  watcher: FSWatcher,
  config?: GtbConfig,
  initialEntries: string[] = [],
) {
  let timeoutId: NodeJS.Timeout | null = setTimeout(() => {
    console.clear();
    printHeader(url, true);
  }, 5000);
  printHeader(url);
  printCompilationDetails(res, null, true);
  printProblems(res);

  const wss = new WebSocketServer({
    port,
  });

  const entries = new Set(initialEntries);
  // Entries whose last build failed: their imports are unknown, so any
  // source change retries them (e.g. a new import that couldn't resolve yet).
  const failed = new Set(res.failedEntries ?? []);
  let firstConnection = true;
  const pending = new Map<string, string>();
  let debounce: ReturnType<typeof setTimeout> | null = null;
  let queue: Promise<void> = Promise.resolve();

  async function refreshEntries(): Promise<string[]> {
    const found = new Set([
      ...(await findEntryPoints("src/js", [".ts", ".js"])),
      ...(await findEntryPoints("src/css", [".css"])),
    ].map((p) => p.replace(/\\/g, "/")));
    for (const old of entries) {
      if (!found.has(old)) {
        entries.delete(old);
        await forgetEntry(old);
      }
    }
    const added = [...found].filter((p) => !entries.has(p));
    added.forEach((p) => entries.add(p));
    return added;
  }

  async function processBatch(batch: Map<string, string>): Promise<void> {
    const reloadReasons: string[] = [];
    const notices: string[] = [];
    const templateLines: string[] = [];
    const imageLines: string[] = [];
    const toBuild = new Set<string>();
    const sources: string[] = [];
    const unknown: string[] = [];
    let renderLayout = false;

    const sourceAddedOrRemoved = [...batch].some(
      ([p, e]) => (e === "add" || e === "unlink") && classifyChange(p, entries) === "source",
    );
    const newEntries = sourceAddedOrRemoved ? await refreshEntries() : [];

    for (const [path, event] of batch) {
      const kind = classifyChange(path, entries);
      switch (kind) {
        case "layout":
          renderLayout = true;
          reloadReasons.push(`layout ${verb(event)}: ${path}`);
          templateLines.push(`${path} ${verb(event)}`);
          break;

        case "template":
          reloadReasons.push(`template ${verb(event)}: ${path}`);
          templateLines.push(`${path} ${verb(event)}`);
          if ((event === "add" || event === "unlink") && !path.includes("/")) {
            notices.push(
              `${path} was ${verb(event)}. Ghost reads the list of templates when it starts, so restart Ghost if the change doesn't show.`,
            );
          }
          break;

        case "source": {
          sources.push(path);
          const affected = dependentsOf(path).filter((e) => entries.has(e));
          if (event !== "unlink" && (entries.has(path) || newEntries.includes(path))) {
            affected.push(path);
          }
          affected.forEach((e) => toBuild.add(e));
          if (event === "unlink") tree.delete(path);
          if (affected.length === 0 && event !== "unlink") unknown.push(path);
          break;
        }

        case "image":
          try {
            if (event === "unlink") {
              await removeImageOutputs(path, process.cwd());
              imageLines.push(`Removed outputs for ${path}`);
            } else {
              await optimizeImage(path, process.cwd());
              imageLines.push(`Optimized image: ${path}`);
            }
            reloadReasons.push(`image ${verb(event)}: ${path}`);
          } catch (e) {
            const msg = e instanceof Error ? e.message : String(e);
            logToFile(`Image optimization error for ${path}: ${msg}`);
            notices.push(`Image optimization failed for ${path}: ${msg}`);
          }
          break;

        case "asset":
          reloadReasons.push(`asset ${verb(event)}: ${path}`);
          break;

        case "package":
          notices.push(
            "package.json changed. Ghost reads theme config (custom settings, posts_per_page, image sizes) when the theme loads: restart Ghost to apply it.",
          );
          break;

        case "locale":
          notices.push(`${path} ${verb(event)}. Ghost loads theme translations when the theme loads: restart Ghost to apply it.`);
          break;

        case "ignore":
          break;
      }
    }

    if (sources.length > 0) {
      for (const e of failed) if (entries.has(e)) toBuild.add(e);
    }

    let build: CompilationDetails | null = null;
    if (toBuild.size > 0) {
      logToFile(`Rebuilding ${[...toBuild].join(", ")} due to ${sources.join(", ")}`);
      build = await writeAssets([...toBuild], port, true, config, {
        renderTemplate: renderLayout,
      });
    } else if (renderLayout) {
      await inlineCritical("assets/built", "default-template.hbs", port);
    }

    if (build) {
      for (const e of toBuild) failed.delete(e);
      for (const e of build.failedEntries ?? []) failed.add(e);
    }

    // Judge "not imported" only once nothing is failing: a broken entry's
    // imports are unknown, and a retry may have just discovered the file.
    if (failed.size === 0) {
      for (const p of unknown) {
        if (dependentsOf(p).length === 0) {
          notices.push(`${p} isn't imported by any entry point, so it isn't in any bundle.`);
        }
      }
    }

    const errors: BuildProblem[] = build?.errors ?? [];
    const outputs = build?.outputs ?? [];

    if (build && errors.length === 0) {
      // Critical CSS is swapped into its inline <style>; critical JS has
      // already run before first paint, so only a reload re-applies it.
      if (outputs.some((o) => o.endsWith(".js") && o.includes("/critical/"))) {
        reloadReasons.push("critical JS changed (inlined in default.hbs)");
      }
      if (outputs.some((o) => o.endsWith(".js") && !o.includes("/critical/"))) {
        reloadReasons.push(`JS changed: ${sources.join(", ")}`);
      }
    }

    const cssOutputs = outputs.filter((o) => o.endsWith(".css"));
    // Critical CSS is listed in `files` too: if the template links it instead
    // of inlining it (non-matching tag), the client swaps the <link>.
    const cssFiles = cssOutputs.map((o) => o.replace(/^assets\//, ""));
    const inline = await Promise.all(
      cssOutputs
        .filter((o) => o.includes("/critical/"))
        .map(async (o) => ({ file: o.replace(/^assets\//, ""), css: await readCriticalCss(o) })),
    );

    if (reloadReasons.length === 0 && notices.length === 0 && !build) return;

    // Terminal
    printHeader(url, false, false);
    if (build && build.results.length > 0) {
      printCompilationDetails(build, sources.join(", "));
    }
    for (const line of templateLines) {
      console.log(chalk.cyanBright("{{  "), `${line}. Reloading...`);
    }
    for (const line of imageLines) console.log(chalk.blue("⬥"), ` ${line}`);
    if (build) printProblems(build);
    for (const notice of notices) console.log(chalk.yellow("⚠"), ` ${notice}`);
    if (templateLines.length || imageLines.length || notices.length) console.log("");

    // Browser
    for (const message of notices) send(wss, { type: "notice", message });
    if (errors.length > 0) {
      send(wss, {
        type: "error",
        file: errors[0].file,
        message: errors.map((e) => e.text).join("\n"),
      });
      // A template edit in the same batch still deserves a reload.
      if (templateLines.length > 0) send(wss, { type: "reload", reason: reloadReasons.join("; ") });
      return;
    }
    if (reloadReasons.length > 0) {
      send(wss, { type: "reload", reason: reloadReasons.join("; ") });
    } else if (cssFiles.length > 0) {
      send(wss, {
        type: "css",
        files: cssFiles,
        source: sources.join(", "),
        ...(inline.length > 0 ? { inline } : {}),
      });
    }
  }

  function flush() {
    debounce = null;
    const batch = new Map(pending);
    pending.clear();
    queue = queue
      .then(() => processBatch(batch))
      .catch((e) => {
        const msg = e instanceof Error ? e.stack ?? e.message : String(e);
        logToFile(`Watcher error: ${msg}`);
        console.error(chalk.red("✘  Unexpected watcher error:"), msg);
      });
  }

  watcher.on("all", (event: string, rawPath: string) => {
    const path = rawPath.replace(/\\/g, "/");
    logToFile(`File event: ${event} on ${path}`);
    if (classifyChange(path, entries) === "ignore") return;
    pending.set(path, event);
    if (debounce) clearTimeout(debounce);
    debounce = setTimeout(flush, DEBOUNCE_MS);
  });

  wss.on("connection", (ws) => {
    if (timeoutId) {
      clearTimeout(timeoutId);
      timeoutId = null;
    }

    if (firstConnection) {
      printHeader(url, false, true);
      firstConnection = false;
    }

    ws.on("message", (message: string) => {
      try {
        const data = JSON.parse(message);
        siteData = data as SiteData;
      } catch (e) {
        // Ignore malformed messages
      }
    });
  });

  watcher.on("close", () => {
    if (timeoutId) {
      clearTimeout(timeoutId);
      timeoutId = null;
    }
    if (debounce) clearTimeout(debounce);
  });

  /** Resolves once every queued batch has been processed (used by tests). */
  return { idle: () => queue };
}
